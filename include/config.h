#pragma once

// ---------- Кнопки (кожна між піном і GND, внутрішня підтяжка INPUT_PULLUP) ----------
#define LOCK_BUTTON_PIN 7    // замок: коротке — відкрити/закрити, довге — валет-режим
#define HAZARD_BUTTON_PIN 0  // аварійка: вбудована кнопка BOOT на платі (GPIO0); коротке — увімк/вимк
#define TURN_BUTTON_PIN 16   // поворотник: клік — лівий, подвійний клік — правий
#define CRASH_SENSOR_PIN 18  // датчик удару: провід-контакт, що торкається GND; коротке — гальмо, довге — аварія

// ---------- Виходи ----------
#define LOCK_RELAY_PIN 17 // реле замка (через транзистор 2N2222): HIGH — замок відкритий
#define LEFT_LED_PIN 4    // лівий поворотник (жовтий)
#define RIGHT_LED_PIN 5   // правий поворотник (жовтий)
#define BRAKE_LED_PIN 6   // стоп-сигнал (червоний)

// ---------- Час ----------
#define DEBOUNCE_MS 30        // кнопка має "заспокоїтись" 30 мс після останнього фронту
#define LONG_PRESS_MS 2000    // довге натискання
#define DOUBLE_CLICK_MS 400   // вікно для другого кліку
#define BLINK_MS 500          // період перемикання поворотників
#define BRAKE_LIGHT_MS 1000   // скільки горить стоп-сигнал після короткого удару
