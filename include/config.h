// ---------- Аналогові входи (ADC1) ----------
#define LDR_PIN 2 // фоторезистор у подільнику: 3V3 -> LDR -> GPIO2 -> 10 кОм -> GND
#define POT_PIN 1 // потенціометр (педаль газу): 3V3 — повзунок на GPIO1 — GND

#define ADC_PERIOD_MS 20 // вимірювання 50 разів на секунду (за таймером, не polling)
#define SMA_WINDOW 16    // фільтр: ковзна середня по 16 вимірюваннях

// Фари: гістерезис по відфільтрованому значенню LDR
#define LIGHT_TH_DARK 1500  // нижче — темно, фари вмикаються
#define LIGHT_TH_LIGHT 1900 // вище — світло, фари вимикаються

// ---------- Фари ----------
#define HEADLIGHT_PIN 15 // білий LED

// ---------- Двигун ----------
#define MOTOR_PIN 14          // через другий транзистор 2N2222
#define MOTOR_LEDC_CHANNEL 2  // свій канал/таймер LEDC
#define MOTOR_PWM_FREQ 20000  // 20 кГц — двигун не пищить
#define MOTOR_START_PCT 5     // нижче — двигун вимкнений (мертва зона)
#define MOTOR_MIN_DUTY 400    // з 0..1023: менше — двигун гуде, але не рушає

// ---------- Дзеркало: серво + енкодер ----------
#define SERVO_PIN 10 // було 21 — на платі погано пропаяний пін
#define SERVO_LEDC_CHANNEL 4 // свій таймер LEDC (50 Гц), не заважає двигуну
#define SERVO_MIN_US 500     // імпульс для 0°
#define SERVO_MAX_US 2500    // імпульс для 180°
#define MIRROR_MIN_ANGLE 30  // межі руху дзеркала
#define MIRROR_MAX_ANGLE 150
#define MIRROR_CENTER 90
#define MIRROR_STEP 5 // градусів на один клік енкодера

#define ENCODER_CLK_PIN 11
#define ENCODER_DT_PIN 12
#define ENCODER_SW_PIN 13       // кнопка енкодера: коротке — дзеркало в центр
#define ENCODER_STEPS_PER_CLICK 4 // переходів квадратурного сигналу на один клік (KY-040: 4, деякі — 2)
